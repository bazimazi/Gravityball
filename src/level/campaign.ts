function compile(list: LevelDraft[]): LevelDef[] {
  return list.map((d) => L(d));
}

export const CAMPAIGN: LevelDef[] = compile([...W1, ...W2, ...W3, ...W4, ...W5, ...W6, ...W7, ...W8, ...W9, ...W10]);
export const SECRET_LEVELS: LevelDef[] = compile(SECRETS);
export const CHALLENGE_LEVELS: LevelDef[] = compile(CHALLENGES);

const ALL = [...CAMPAIGN, ...SECRET_LEVELS, ...CHALLENGE_LEVELS];
const BY_ID = new Map(ALL.map((l) => [l.id, l]));

export function getLevel(id: string): LevelDef | undefined {
  return BY_ID.get(id);
}

export function worldLevels(world: number): LevelDef[] {
  return CAMPAIGN.filter((l) => l.world === world).concat(SECRET_LEVELS.filter((l) => l.world === world));
}

export function nextCampaign(id: string): LevelDef | undefined {
  const i = CAMPAIGN.findIndex((l) => l.id === id);
  if (i < 0) return undefined;
  return CAMPAIGN[i + 1];
}

export function isLastInWorld(id: string): boolean {
  const level = BY_ID.get(id);
  if (!level || level.secret || level.challenge) return false;
  const mates = CAMPAIGN.filter((l) => l.world === level.world);
  return mates[mates.length - 1]?.id === id;
}

export function dailyPool(): LevelDef[] {
  return ALL.filter((l) => l.tags?.includes('daily'));
}

export function endlessPool(): LevelDef[] {
  return ALL.filter((l) => l.tags?.includes('endless'));
}

export const FRAGMENTS: { id: string; line: string }[] = ALL.flatMap((l) =>
  l.fragments.map((f) => ({ id: f.id, line: f.line })),
);
